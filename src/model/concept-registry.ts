export const CONCEPT_MAP = new Map<string, Concept>(
  CONCEPTS.map((c) => [c.id, c])
);

export const CONCEPT_SLUG_MAP = new Map<string, Concept>(
  CONCEPTS.map((c) => [`${c.categorySlug}/${c.slug}`, c])
);

export function getConceptById(id: string): Concept | undefined {
  return CONCEPT_MAP.get(id);
}

export function getConceptBySlug(categorySlug: string, conceptSlug: string): Concept | undefined {
  return CONCEPT_SLUG_MAP.get(`${categorySlug}/${conceptSlug}`) || CONCEPTS.find(c => c.slug === conceptSlug);
}
